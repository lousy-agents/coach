package codesignalcli

import (
	"testing"

	"github.com/lousy-agents/coach/internal/codesignalcli/gitrepo"
)

func TestChangedFilesFromStatusLeavesOutSourceFilesUnderNodeModules(t *testing.T) {
	entries := []gitrepo.WorktreeEntry{
		{Code: " M", Path: "node_modules/pkg/index.ts"},
		{Code: "??", Path: "web/node_modules/pkg/lib.go"},
		{Code: "A ", Path: "node_modules/pkg/added.ts"},
		{Code: "??", Path: "src/fresh.ts"},
	}

	got := changedFilesFromStatus(entries, nil)

	if len(got) != 1 || got[0].Path != "src/fresh.ts" || got[0].Status != "added" {
		t.Errorf("changedFilesFromStatus = %+v, want only src/fresh.ts as an added file: a dependency under node_modules is not the project's source", got)
	}
}
