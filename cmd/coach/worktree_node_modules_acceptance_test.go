package main

import (
	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

// The scan does not overlay a vendored dependency tree: it reads the committed
// bytes for anything under node_modules, so an edit there is not analyzed. It is
// disclosed rather than ignored, because a clean verdict would describe bytes the
// scan did not read. This is a known limit of the experimental mode.
var _ = Describe("coach codesignal --worktree for a tracked file under node_modules that is edited", func() {
	It("names the file as unanalyzed and exits 3, instead of reading it or ignoring it", func() {
		repo := goOverlayRepo()
		commitFile(repo, "node_modules/dep/dep.go", "package dep\n")
		overwriteOnDisk(repo, "node_modules/dep/dep.go", "package dep\n\nvar Edited = 1\n")
		expectDirtyPorcelain(repo, " M node_modules/dep/dep.go")

		stdout, stderr, exitCode := runCoachCodesignalBaselineRaw(repo, "--worktree", "--fail-on-incomplete-coverage", "--format=json")

		Expect(exitCode).To(Equal(3), "stderr: %s stdout: %s", stderr, stdout)
		Expect(diagnosticsOfKind(decodeCoachReport(stdout).Diagnostics, "worktree_changes_not_analyzed")).To(ConsistOf(
			HaveField("Path", "node_modules/dep/dep.go")))
	})
})
